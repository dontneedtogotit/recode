//! Manifest budget and dependency resolution (P1.7).
//!
//! Pure domain module — no stores, no DI, no I/O. Turns a flat list of
//! manifest files with explicit `depends_on` edges into wave-ordered,
//! budget-bounded generation batches. A dependency cycle is a hard error:
//! generation cannot proceed when the file graph is not a DAG.
//!
//! Ported from devcode `GenerationManifestBuilder`'s wave/dependency logic,
//! adapted to recode's flat module layout and `DomainError` conventions.
//! devcode's orchestrator glue (IParallelLLMExecutor, AIBatchExecutor,
//! IDomainEventBus) is out of scope — only the pure graph + budget math.

use crate::domain::{DomainError, Result};
use std::collections::{BTreeMap, BTreeSet};

/// Per-run resource budget caps. A manifest that exceeds any cap is rejected
/// at build time, not discovered mid-generation.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct ManifestBudget {
    /// Upper bound on the sum of every file's `max_tokens`.
    pub max_total_tokens: usize,
    /// Upper bound on the number of files.
    pub max_files: usize,
    /// Upper bound on generated bytes across all files.
    pub max_total_bytes: usize,
    /// Upper bound on generation concurrency (parallel in-flight requests).
    pub max_concurrency: usize,
    /// Upper bound on total wall-clock seconds for the whole run.
    pub max_wall_seconds: u64,
}

impl Default for ManifestBudget {
    fn default() -> Self {
        Self {
            max_total_tokens: 196_608, // 12 files × 16K cap, rounded.
            max_files: 48,
            max_total_bytes: 256 * 1024,
            max_concurrency: 4,
            max_wall_seconds: 600,
        }
    }
}

/// A file with explicit dependencies, ready for wave assignment.
#[derive(Debug, Clone, PartialEq, Eq)]
#[allow(dead_code)]  // used by tests; production wiring pending
pub struct DependencyFile {
    pub path: String,
    /// Paths this file imports or requires to exist before it can generate
    /// correctly. Edges point from this file to its dependencies.
    pub depends_on: Vec<String>,
}

/// Assigns a wave number to each file so that every dependency is generated
/// in an earlier wave. Returns the files in non-decreasing wave order.
///
/// `max_waves` bounds the depth; a deeper graph (or a cycle) returns
/// `Err(DomainError::invalid_input)` rather than spinning. The algorithm is
/// Kahn's: repeatedly emit files whose dependencies are all already emitted,
/// removing them from the pending set each pass.
#[allow(dead_code)]  // used by tests; production wiring pending
pub fn resolve_waves(files: &[DependencyFile], max_waves: usize) -> Result<Vec<(String, u8)>> {
    if files.is_empty() {
        return Ok(Vec::new());
    }
    let known: BTreeSet<&str> = files.iter().map(|f| f.path.as_str()).collect();
    // Validate that every declared dependency is a known file; dangling edges
    // are a hard error because they would silently drop the constraint.
    for file in files {
        for dep in &file.depends_on {
            if !known.contains(dep.as_str()) {
                return Err(DomainError::invalid_input(format!(
                    "manifest file {} depends on unknown path {}",
                    file.path, dep
                )));
            }
        }
    }
    let mut emitted: BTreeSet<String> = BTreeSet::new();
    let mut ordered = Vec::with_capacity(files.len());
    let mut wave: u8 = 0;
    let mut pending: Vec<&DependencyFile> = files.iter().collect();
    while !pending.is_empty() {
        if wave as usize >= max_waves {
            return Err(DomainError::invalid_input(
                "manifest dependency graph exceeds the wave limit (cycle or too deep)",
            ));
        }
        // Files whose dependencies are all already emitted go in this wave.
        let mut ready: Vec<&DependencyFile> = Vec::new();
        let mut still_pending: Vec<&DependencyFile> = Vec::new();
        for file in &pending {
            let all_deps_emitted = file.depends_on.iter().all(|d| emitted.contains(d));
            if all_deps_emitted {
                ready.push(file);
            } else {
                still_pending.push(file);
            }
        }
        if ready.is_empty() {
            // No progress this wave → every remaining file has an unmet
            // dependency that is itself still pending → cycle.
            let remaining: Vec<&str> = pending.iter().map(|f| f.path.as_str()).collect();
            return Err(DomainError::invalid_input(format!(
                "manifest dependency graph has a cycle among: {}",
                remaining.join(", ")
            )));
        }
        for file in &ready {
            ordered.push((file.path.clone(), wave));
            emitted.insert(file.path.clone());
        }
        pending = still_pending;
        wave += 1;
    }
    Ok(ordered)
}

/// Compute `max_tokens = clamp(expected_loc × 80, 2_000, 16_000)`.
///
/// The roadmap's per-file token budget formula. `expected_loc` is the
/// planner's estimate of the file's line count; the clamp floors at 2K so a
/// tiny file still gets room for imports/boilerplate, and caps at 16K so a
/// single file cannot monopolize the response budget.
pub fn max_tokens_for_loc(expected_loc: usize) -> usize {
    (expected_loc.saturating_mul(80)).max(2_048).min(16_384)
}

/// Validate a manifest's aggregate budget. Returns the total tokens/bytes
/// and file count, or the first exceeded cap as an error. Pure — does not
/// mutate the manifest.
pub fn validate_budget(
    file_count: usize,
    total_tokens: usize,
    total_bytes: usize,
    budget: &ManifestBudget,
) -> Result<()> {
    if file_count > budget.max_files {
        return Err(DomainError::invalid_input(format!(
            "manifest has {} files but the per-run limit is {}",
            file_count, budget.max_files
        )));
    }
    if total_tokens > budget.max_total_tokens {
        return Err(DomainError::invalid_input(format!(
            "manifest total tokens {} exceed the per-run limit {}",
            total_tokens, budget.max_total_tokens
        )));
    }
    if total_bytes > budget.max_total_bytes {
        return Err(DomainError::invalid_input(format!(
            "manifest total bytes {} exceed the per-run limit {}",
            total_bytes, budget.max_total_bytes
        )));
    }
    Ok(())
}

/// Build a path → wave index lookup from an ordered wave list.
#[allow(dead_code)]  // used by tests; production wiring pending
pub fn wave_map(ordered: &[(String, u8)]) -> BTreeMap<String, u8> {
    ordered.iter().cloned().collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dep(path: &str, depends_on: &[&str]) -> DependencyFile {
        DependencyFile {
            path: path.into(),
            depends_on: depends_on.iter().map(|s| s.to_string()).collect(),
        }
    }

    #[test]
    fn no_dependencies_all_wave_zero() {
        let files = vec![dep("a.ts", &[]), dep("b.ts", &[])];
        let waves = resolve_waves(&files, 8).unwrap();
        assert_eq!(waves.len(), 2);
        assert!(waves.iter().all(|(_, w)| *w == 0));
    }

    #[test]
    fn dependency_advances_wave() {
        let files = vec![dep("a.ts", &[]), dep("b.ts", &["a.ts"])];
        let waves = resolve_waves(&files, 8).unwrap();
        let map = wave_map(&waves);
        assert_eq!(map.get("a.ts").copied(), Some(0));
        assert_eq!(map.get("b.ts").copied(), Some(1));
    }

    #[test]
    fn transitive_chain_increments_wave_each_step() {
        let files = vec![
            dep("a.ts", &[]),
            dep("b.ts", &["a.ts"]),
            dep("c.ts", &["b.ts"]),
        ];
        let waves = resolve_waves(&files, 8).unwrap();
        let map = wave_map(&waves);
        assert_eq!(map.get("a.ts").copied(), Some(0));
        assert_eq!(map.get("b.ts").copied(), Some(1));
        assert_eq!(map.get("c.ts").copied(), Some(2));
    }

    #[test]
    fn diamond_dependency_shares_wave() {
        // a → b, a → c, b → d, c → d: b and c both wave 1, d wave 2.
        let files = vec![
            dep("a.ts", &[]),
            dep("b.ts", &["a.ts"]),
            dep("c.ts", &["a.ts"]),
            dep("d.ts", &["b.ts", "c.ts"]),
        ];
        let waves = resolve_waves(&files, 8).unwrap();
        let map = wave_map(&waves);
        assert_eq!(map.get("a.ts").copied(), Some(0));
        assert_eq!(map.get("b.ts").copied(), Some(1));
        assert_eq!(map.get("c.ts").copied(), Some(1));
        assert_eq!(map.get("d.ts").copied(), Some(2));
    }

    #[test]
    fn cycle_detected() {
        let files = vec![dep("a.ts", &["b.ts"]), dep("b.ts", &["a.ts"])];
        let result = resolve_waves(&files, 8);
        assert!(result.is_err());
        let err = result.unwrap_err().to_string();
        assert!(err.contains("cycle"), "error must mention cycle: {err}");
    }

    #[test]
    fn self_cycle_detected() {
        let files = vec![dep("a.ts", &["a.ts"])];
        let result = resolve_waves(&files, 8);
        assert!(result.is_err());
    }

    #[test]
    fn unknown_dependency_rejected() {
        let files = vec![dep("a.ts", &["ghost.ts"])];
        let result = resolve_waves(&files, 8);
        assert!(result.is_err());
        assert!(result.unwrap_err().to_string().contains("unknown path"));
    }

    #[test]
    fn wave_limit_exceeded_treated_as_cycle() {
        // A chain longer than max_waves is rejected even without a true cycle.
        let files = vec![
            dep("a.ts", &[]),
            dep("b.ts", &["a.ts"]),
            dep("c.ts", &["b.ts"]),
        ];
        let result = resolve_waves(&files, 2);
        assert!(result.is_err());
    }

    #[test]
    fn empty_manifest_resolves_to_empty() {
        let waves = resolve_waves(&[], 8).unwrap();
        assert!(waves.is_empty());
    }

    #[test]
    fn max_tokens_clamps_loc_formula() {
        // floor 2K for tiny files
        assert_eq!(max_tokens_for_loc(0), 2_048);
        assert_eq!(max_tokens_for_loc(10), 2_048); // 10×80=800 < 2K → floor
        // exact formula in the middle
        assert_eq!(max_tokens_for_loc(50), 4_000); // 50×80=4000
        assert_eq!(max_tokens_for_loc(100), 8_000); // 100×80=8000
        // cap 16K for large files
        assert_eq!(max_tokens_for_loc(200), 16_000); // 200×80=16000
        assert_eq!(max_tokens_for_loc(300), 16_384); // 300×80=24000 → cap
        assert_eq!(max_tokens_for_loc(usize::MAX), 16_384); // saturating
    }

    #[test]
    fn budget_validation_rejects_overages() {
        let budget = ManifestBudget::default();
        assert!(validate_budget(10, 100_000, 64 * 1024, &budget).is_ok());
        // too many files
        let err = validate_budget(budget.max_files + 1, 100, 100, &budget);
        assert!(err.is_err());
        assert!(err.unwrap_err().to_string().contains("files"));
        // too many tokens
        let err = validate_budget(10, budget.max_total_tokens + 1, 100, &budget);
        assert!(err.is_err());
        assert!(err.unwrap_err().to_string().contains("tokens"));
        // too many bytes
        let err = validate_budget(10, 100, budget.max_total_bytes + 1, &budget);
        assert!(err.is_err());
        assert!(err.unwrap_err().to_string().contains("bytes"));
    }

    #[test]
    fn budget_allows_exact_limits() {
        let budget = ManifestBudget::default();
        assert!(validate_budget(budget.max_files, budget.max_total_tokens, budget.max_total_bytes, &budget).is_ok());
    }
}
